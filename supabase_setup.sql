-- Employee Profiles Table (Employee Portal)
CREATE TABLE IF NOT EXISTS public.employee_profiles (
    id SERIAL PRIMARY KEY,
    auth_user_id UUID UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    employee_id TEXT UNIQUE NOT NULL,
    role TEXT NOT NULL,
    approval_status TEXT DEFAULT 'pending' CHECK (approval_status IN ('pending', 'approved', 'rejected')),
    disabled BOOLEAN DEFAULT false,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- Salary Components Table
CREATE TABLE IF NOT EXISTS public.salary_components (
    id SERIAL PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('earning', 'deduction')),
    attendance_based BOOLEAN DEFAULT false,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- Employee Salary Structure (Bridge Table)
CREATE TABLE IF NOT EXISTS public.employee_salary_structure (
    id SERIAL PRIMARY KEY,
    employee_profile_id INT REFERENCES public.employee_profiles(id) ON DELETE CASCADE,
    component_id INT REFERENCES public.salary_components(id) ON DELETE CASCADE,
    amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE (employee_profile_id, component_id)
);

-- Attendance Records Table
CREATE TABLE IF NOT EXISTS public.attendance_records (
    id SERIAL PRIMARY KEY,
    employee_profile_id INT REFERENCES public.employee_profiles(id) ON DELETE CASCADE,
    date DATE NOT NULL,
    check_in_time TIMESTAMPTZ DEFAULT now(),
    status TEXT DEFAULT 'present' CHECK (status IN ('present', 'absent', 'half_day', 'late')),
    created_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE (employee_profile_id, date)
);

-- Payslips Table
CREATE TABLE IF NOT EXISTS public.payslips (
    id SERIAL PRIMARY KEY,
    employee_profile_id INT REFERENCES public.employee_profiles(id) ON DELETE CASCADE,
    month TEXT NOT NULL, -- Format: YYYY-MM
    basic_salary DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    hra DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    travel_allowance DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    bonus DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    pf_deduction DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    tax_deduction DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    other_earnings DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    other_deductions DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    custom_components JSONB DEFAULT '{}'::jsonb,
    total_present_days NUMERIC(4, 1) NOT NULL DEFAULT 0.0,
    total_working_days INT NOT NULL,
    gross_salary DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    total_deductions DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    net_salary DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE (employee_profile_id, month)
);


