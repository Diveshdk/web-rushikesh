-- ==========================================
-- 4. AUTH TRIGGER FOR AUTO-CREATING PROFILES
-- ==========================================

-- Create/replace trigger function for handling new auth user registration
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    new_employee_id TEXT;
BEGIN
    -- Derive a default/custom employee ID from metadata, or fallback to UUID snippet
    new_employee_id := COALESCE(
        new.raw_user_meta_data->>'employee_id', 
        'RSA-' || UPPER(SUBSTRING(new.id::text FROM 1 FOR 8))
    );

    INSERT INTO public.employee_profiles (
        auth_user_id,
        full_name,
        email,
        phone,
        employee_id,
        role,
        approval_status,
        disabled
    ) VALUES (
        new.id,
        COALESCE(new.raw_user_meta_data->>'full_name', 'Employee'),
        new.email,
        new.raw_user_meta_data->>'phone',
        new_employee_id,
        COALESCE(new.raw_user_meta_data->>'role', 'Employee'),
        'pending',
        false
    );
    
    RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Bind the trigger function to the auth.users table
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


