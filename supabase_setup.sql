-- ------------------------------------------
-- RLS: Public Tables (Projects, Gallery, etc.)
-- ------------------------------------------

-- Allow public read access to everyone
CREATE POLICY "Public Read Projects" ON public.projects FOR SELECT USING (true);
CREATE POLICY "Public Read Gallery" ON public.gallery FOR SELECT USING (true);
CREATE POLICY "Public Read Instagram Posts" ON public.instagram_posts FOR SELECT USING (true);
CREATE POLICY "Public Read Testimonials" ON public.testimonials FOR SELECT USING (true);
CREATE POLICY "Public Read Jobs" ON public.jobs FOR SELECT USING (true);
CREATE POLICY "Public Read Employees" ON public.employees FOR SELECT USING (true);
CREATE POLICY "Public Read Images" ON public.images FOR SELECT USING (true);
CREATE POLICY "Public Read Test" ON public.test FOR SELECT USING (true);

-- Allow writes to portfolio tables
-- SECURITY NOTE: The admin panel (/youcantseeme) makes client-side updates using the Supabase client
-- with the Anon Key (without a Supabase auth login). To keep it functioning, these policies 
-- allow direct writes. 
-- In a strictly secured production environment, you should transition the admin panel to utilize 
-- Supabase Auth and change the ALL policies below from "TO public" / "USING (true)" to "TO authenticated".
CREATE POLICY "Admin Write Projects" ON public.projects FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Admin Write Gallery" ON public.gallery FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Admin Write Instagram Posts" ON public.instagram_posts FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Admin Write Testimonials" ON public.testimonials FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Admin Write Jobs" ON public.jobs FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Admin Write Employees" ON public.employees FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Admin Write Images" ON public.images FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Admin Write Test" ON public.test FOR ALL USING (true) WITH CHECK (true);

-- ------------------------------------------
-- RLS: Employee Portal (Secure Tables)
-- ------------------------------------------

-- Note: Server Actions (Prisma) run with admin/superuser permissions, bypassing RLS.
-- These policies secure direct client-side reads by logged-in employees.

-- Employee Profiles
CREATE POLICY "Employees can read own profile" ON public.employee_profiles
    FOR SELECT TO authenticated USING (auth.uid() = auth_user_id);

CREATE POLICY "Employees can update own profile" ON public.employee_profiles
    FOR UPDATE TO authenticated USING (auth.uid() = auth_user_id) WITH CHECK (auth.uid() = auth_user_id);

-- Salary Components
CREATE POLICY "Authenticated users can read salary categories" ON public.salary_components
    FOR SELECT TO authenticated USING (true);

-- Salary Structure
CREATE POLICY "Employees can read own salary structure" ON public.employee_salary_structure
    FOR SELECT TO authenticated USING (
        employee_profile_id IN (
            SELECT id FROM public.employee_profiles WHERE auth_user_id = auth.uid()
        )
    );

-- Attendance Records
CREATE POLICY "Employees can read own attendance" ON public.attendance_records
    FOR SELECT TO authenticated USING (
        employee_profile_id IN (
            SELECT id FROM public.employee_profiles WHERE auth_user_id = auth.uid()
        )
    );

-- Payslips
CREATE POLICY "Employees can read own payslips" ON public.payslips
    FOR SELECT TO authenticated USING (
        employee_profile_id IN (
            SELECT id FROM public.employee_profiles WHERE auth_user_id = auth.uid()
        )
    );

-- ------------------------------------------
-- RLS: Storage Bucket Policies (images)
-- ------------------------------------------

-- Enable read access to the images bucket for everyone
CREATE POLICY "Public Read Images Bucket" ON storage.objects
    FOR SELECT USING (bucket_id = 'images');

-- Enable upload/insert access for public/authenticated users to the images bucket
CREATE POLICY "Allow Upload Images Bucket" ON storage.objects
    FOR INSERT WITH CHECK (bucket_id = 'images');

-- Enable delete access to the images bucket
CREATE POLICY "Allow Delete Images Bucket" ON storage.objects
    FOR DELETE USING (bucket_id = 'images');
